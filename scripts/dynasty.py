def _matches(label):
    """按长度优先找出 label 中出现的朝代名及其位置。"""
    found = []
    i = 0
    names = sorted(CANON, key=lambda x: -len(x[0]))
    while i < len(label):
        hit = None
        for name, s, e, p in names:
            if label.startswith(name, i):
                hit = (name, s, e, p)
                break
        if hit:
            found.append((i, hit))
            i += len(hit[0])
        else:
            i += 1
    return found


def normalize(label):
    """返回 (分期, 归一朝代, 起始年, 结束年, 中间年)。"""
    label = (label or "").strip()
    if not label:
        return ("近現代", "未詳", 1840, 2026, 1950)
    found = _matches(label)
    if not found:
        return ("近現代", label, 1840, 2026, 1950)
    # 以第一处出现的朝代为「主朝代」
    main = found[0][1]
    period = main[3]
    start, end = main[1], main[2]
    # 「初 / 中 / 晚 / 末」修饰：若紧邻朝代名前后
    prefix = label[max(0, found[0][0] - 2):found[0][0]]
    suffix = label[found[0][0] + len(main[0]):found[0][0] + len(main[0]) + 2]
    span = max(end - start, 1)
    if "初" in prefix and "末" not in prefix:
        start, end = start, start + span // 3
    elif "末" in prefix or "晚" in prefix:
        start, end = end - span // 3, end
    if "初" in suffix and "末" not in suffix:
        start, end = start, start + span // 3
    elif "末" in suffix or "晚" in suffix:
        start, end = end - span // 3, end
    if len(found) > 1:
        last = found[-1][1]
        if last[1] >= main[2] - 20:          # 真正的跨代标签
            mid = (main[2] + last[1]) / 2
        else:                                # 「春秋晉國」这类地域/国别限定
            mid = (start + end) / 2
    else:
        mid = (start + end) / 2
    name = main[0]
    if any(k in label for k in ("民國", "現當代", "當代", "近現代", "現代")) and mid >= 1840:
        period = "近現代"
    if name in ("宋",):
        name = "宋"
    return (period, name, start, end, mid)
